/**
 * Builds the ask.osify.com redirect site.
 *
 * The archive now lives entirely on osify.com, but ask.osify.com has thirteen
 * years of inbound links pointing at /qa/<id>. Rather than letting the
 * subdomain go dark, it becomes its own tiny GitHub Pages site whose only job
 * is to forward every old URL to the article's new home.
 *
 * Deploy the generated `redirects/ask.osify.com/` directory as a separate
 * GitHub Pages repository with a DNS CNAME for ask.osify.com.
 *
 *   node scripts/build-ask-redirects.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import matter from 'gray-matter';
import { SITE_ROOT, ensureDir } from './lib/util.mjs';

const POSTS_DIR = path.join(SITE_ROOT, 'src', 'content', 'posts');
const TARGET_ORIGIN = 'https://osify.com';

/**
 * Output lives outside this project by default.
 *
 * GitHub Pages binds one custom domain per repository, via the single CNAME at
 * the site root, so ask.osify.com cannot be served from the osify.com repo. It
 * needs its own repository — hence its own working directory, a sibling rather
 * than a nested folder (git treats a repo inside a repo as an embedded
 * repository and refuses to track it usefully).
 *
 * Override with `--out <dir>`.
 */
const outFlag = process.argv.indexOf('--out');
const OUT_ROOT =
  outFlag !== -1 && process.argv[outFlag + 1]
    ? path.resolve(process.argv[outFlag + 1])
    : path.resolve(SITE_ROOT, '..', 'ask-osify-redirect');

/** Regenerating must not destroy the target repo's history or git config. */
const PRESERVE = new Set(['.git', '.gitattributes', '.gitignore']);

function clearGenerated(dir) {
  if (!fs.existsSync(dir)) return;
  for (const entry of fs.readdirSync(dir)) {
    if (PRESERVE.has(entry)) continue;
    fs.rmSync(path.join(dir, entry), { recursive: true, force: true });
  }
}

function page({ target, title, immediate = true }) {
  const escaped = String(title).replace(/[&<>]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;' })[c]);
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Moved — ${escaped}</title>
<link rel="canonical" href="${target}">
<meta http-equiv="refresh" content="0; url=${target}">
<meta name="robots" content="noindex, follow">
${immediate ? `<script>window.location.replace(${JSON.stringify(target)});</script>` : ''}
<style>
body{font-family:system-ui,sans-serif;max-width:34rem;margin:20vh auto;padding:0 1.5rem;line-height:1.6;color:#11141b}
a{color:#3a31c4}
@media(prefers-color-scheme:dark){body{background:#0c0e13;color:#e3e6ec}a{color:#9b94ff}}
</style>
</head>
<body>
<p>ask.osify.com has moved to <a href="${TARGET_ORIGIN}/">osify.com</a>.</p>
<p><a href="${target}">${escaped}</a></p>
</body>
</html>
`;
}

function write(relPath, html) {
  const abs = path.join(OUT_ROOT, relPath);
  ensureDir(path.dirname(abs));
  fs.writeFileSync(abs, html, 'utf8');
}

function main() {
  if (!fs.existsSync(POSTS_DIR)) {
    console.error('No migrated posts found — run `npm run migrate` first.');
    process.exit(1);
  }

  clearGenerated(OUT_ROOT);
  ensureDir(OUT_ROOT);

  let count = 0;
  const seen = new Set();

  for (const name of fs.readdirSync(POSTS_DIR)) {
    if (!name.endsWith('.md')) continue;
    const slug = name.replace(/\.md$/, '');
    const { data } = matter(fs.readFileSync(path.join(POSTS_DIR, name), 'utf8'));

    for (const legacyUrl of data.legacyUrls || []) {
      let url;
      try {
        url = new URL(legacyUrl);
      } catch {
        continue;
      }
      if (url.host !== 'ask.osify.com') continue;

      const key = url.pathname.replace(/^\/|\/$/g, '');
      if (!key || seen.has(key)) continue;
      seen.add(key);

      const target = `${TARGET_ORIGIN}/posts/${slug}/`;
      write(path.join(key, 'index.html'), page({ target, title: data.title }));
      count++;
    }
  }

  // Anything unmapped lands on the archive rather than a dead end.
  write('index.html', page({ target: `${TARGET_ORIGIN}/`, title: 'The OSIFY archive' }));
  write('404.html', page({ target: `${TARGET_ORIGIN}/archive/`, title: 'Browse the archive' }));
  write('qa/index.html', page({ target: `${TARGET_ORIGIN}/archive/`, title: 'Browse the archive' }));

  fs.writeFileSync(path.join(OUT_ROOT, 'CNAME'), 'ask.osify.com\n', 'utf8');
  fs.writeFileSync(
    path.join(OUT_ROOT, 'robots.txt'),
    `User-agent: *\nAllow: /\nSitemap: ${TARGET_ORIGIN}/sitemap-index.xml\n`,
    'utf8'
  );
  fs.writeFileSync(
    path.join(OUT_ROOT, 'README.md'),
    `# ask.osify.com — redirects only\n\nGenerated by \`scripts/build-ask-redirects.mjs\` in the osify-website repo.\nDo not edit by hand; regenerate and republish instead.\n\nEvery \`/qa/<id>\` URL forwards to its article on ${TARGET_ORIGIN}.\nEverything else forwards to ${TARGET_ORIGIN}/archive/.\n\n## Deploying\n\nPush this directory to its own GitHub repository with Pages enabled\n(branch \`main\`, folder \`/\`), then point a DNS CNAME record for\n\`ask.osify.com\` at \`<owner>.github.io\`.\n`,
    'utf8'
  );

  console.log(`ask.osify.com redirect site written to ${OUT_ROOT}`);
  console.log(`  ${count} article redirects + index, 404 and /qa fallbacks`);
  console.log(`  existing .git preserved — commit and push from that directory`);
}

main();
